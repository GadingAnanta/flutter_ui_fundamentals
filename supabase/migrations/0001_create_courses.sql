do $$
begin
  if exists (
        select 1 from information_schema.tables
        where table_schema = 'public' and table_name = 'course')
     and not exists (
        select 1 from information_schema.tables
        where table_schema = 'public' and table_name = 'courses')
  then
    alter table public.course rename to courses;
  end if;
end $$;
-- 1) Tabel courses
create table if not exists public.courses (
  id         bigint generated by default as identity primary key,
  code       text        not null,
  title      text        not null,
  credits    int         not null default 0 check (credits >= 0),
  status     text        not null default 'planned'
                         check (status in ('planned', 'active', 'done')),
  created_at timestamptz not null default now()
);

alter table public.courses add column if not exists code       text;
alter table public.courses add column if not exists title      text;
alter table public.courses add column if not exists credits    int default 0;
alter table public.courses add column if not exists status     text default 'planned';
alter table public.courses add column if not exists created_at timestamptz default now();

-- code unik: kunci favorites di aplikasi memakai code.
create unique index if not exists courses_code_key
  on public.courses (code);

-- 2) Hak akses untuk client (anon / publishable key)

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.courses to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;


-- 3) RLS + policy


alter table public.courses enable row level security;

drop policy if exists courses_all_lab on public.courses;
create policy courses_all_lab on public.courses
  for all
  to anon, authenticated
  using (true)
  with check (true);


